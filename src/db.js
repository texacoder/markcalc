// Storage. Works with:
//  - a local SQLite file (file:./data/markcalc.db, the default)
//  - a free hosted Turso database (libsql://…)
//  - a free hosted Postgres database such as Neon or Supabase (postgres://…)
// so the app can run on hosts without a persistent disk.
const fs = require('fs');
const path = require('path');
const { createClient } = require('@libsql/client');

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS exams (
  id INTEGER PRIMARY KEY,
  user_id INTEGER NOT NULL,
  title TEXT NOT NULL,
  subject TEXT NOT NULL DEFAULT '',
  class_name TEXT NOT NULL DEFAULT '',
  total_marks TEXT NOT NULL DEFAULT '',
  syllabus TEXT NOT NULL DEFAULT '',
  scheme TEXT NOT NULL DEFAULT '',
  extra TEXT NOT NULL DEFAULT '',
  question_text TEXT NOT NULL DEFAULT '',
  presets TEXT NOT NULL DEFAULT '[]',
  instructions TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS exam_files (
  id INTEGER PRIMARY KEY,
  exam_id INTEGER NOT NULL,
  position INTEGER NOT NULL,
  mimetype TEXT NOT NULL,
  data BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS results (
  id INTEGER PRIMARY KEY,
  exam_id INTEGER NOT NULL,
  student_name TEXT NOT NULL DEFAULT '',
  roll_no TEXT NOT NULL DEFAULT '',
  total_awarded REAL NOT NULL,
  total_maximum REAL NOT NULL,
  data TEXT NOT NULL,
  edited INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS usage (
  user_id INTEGER NOT NULL,
  day TEXT NOT NULL,
  count INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day)
);
CREATE TABLE IF NOT EXISTS site_usage (
  day TEXT PRIMARY KEY,
  count INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_exams_user ON exams(user_id);
CREATE INDEX IF NOT EXISTS idx_files_exam ON exam_files(exam_id);
CREATE INDEX IF NOT EXISTS idx_results_exam ON results(exam_id);
`;

// Plain objects so rows can be spread / serialized normally.
function toObject(row, columns) {
  if (!row) return undefined;
  const out = {};
  columns.forEach((c, i) => (out[c] = row[i]));
  return out;
}

// Small promise API shared by the client and by transactions.
function wrap(executor) {
  const exec = (sql, args) => executor.execute({ sql, args: args.map((a) => (typeof a === 'boolean' ? Number(a) : a)) });
  return {
    async get(sql, ...args) {
      const r = await exec(sql, args);
      return toObject(r.rows[0], r.columns);
    },
    async all(sql, ...args) {
      const r = await exec(sql, args);
      return r.rows.map((row) => toObject(row, r.columns));
    },
    async run(sql, ...args) {
      const r = await exec(sql, args);
      return { lastInsertRowid: r.lastInsertRowid == null ? null : Number(r.lastInsertRowid), changes: r.rowsAffected };
    },
  };
}

function resolveUrl(url) {
  const value = url || 'file:./data/markcalc.db';
  if (value.startsWith('file:')) {
    const file = value.slice(5);
    if (file && file !== ':memory:') fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  }
  return value;
}

// ---------------- Postgres ----------------

const PG_SCHEMA = SCHEMA.replace(/id INTEGER PRIMARY KEY/g, 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/BLOB/g, 'BYTEA')
  .replace(/REAL/g, 'DOUBLE PRECISION')
  .replace(/(user_id|exam_id|position|count|edited) INTEGER/g, '$1 BIGINT')
  .replace(/expires_at INTEGER/g, 'expires_at BIGINT')
  .replace(/datetime\('now'\)/g, "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')");

// Translate the app's SQLite-flavoured SQL to Postgres.
function toPg(sql) {
  let n = 0;
  let out = sql
    .replace(/datetime\('now'\)/g, "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/\?/g, () => `$${++n}`);
  if (/^\s*INSERT INTO (users|exams|exam_files|results)\b/i.test(out) && !/RETURNING/i.test(out)) out += ' RETURNING id';
  return out;
}

function wrapPg(executor) {
  const exec = (sql, args) => executor.query(toPg(sql), args);
  return {
    async get(sql, ...args) {
      return (await exec(sql, args)).rows[0];
    },
    async all(sql, ...args) {
      return (await exec(sql, args)).rows;
    },
    async run(sql, ...args) {
      const r = await exec(sql, args);
      return { lastInsertRowid: r.rows?.[0]?.id ?? null, changes: r.rowCount };
    },
  };
}

async function openPostgres(url) {
  const pg = require('pg');
  pg.types.setTypeParser(20, (v) => Number(v)); // BIGINT → number
  pg.types.setTypeParser(1700, (v) => parseFloat(v)); // NUMERIC → number
  const local = /@(localhost|127\.0\.0\.1)[:/]/.test(url);
  const pool = new pg.Pool({
    connectionString: url,
    max: 5,
    idleTimeoutMillis: 30000,
    ...(local || /sslmode=/.test(url) ? {} : { ssl: { rejectUnauthorized: true } }),
  });
  // Hosted databases drop idle connections; don't crash on that.
  pool.on('error', (err) => console.error('Database connection error:', err.message));
  await pool.query(PG_SCHEMA);

  const db = wrapPg(pool);
  db.tx = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const out = await fn(wrapPg(client));
      await client.query('COMMIT');
      return out;
    } catch (err) {
      await client.query('ROLLBACK').catch(() => {});
      throw err;
    } finally {
      client.release();
    }
  };
  db.close = () => pool.end();
  return db;
}

// ---------------- entry point ----------------

async function openDb({ url, authToken } = {}) {
  if (/^postgres(ql)?:\/\//i.test(url || '')) return openPostgres(url);
  const client = createClient({ url: resolveUrl(url), authToken: authToken || undefined });
  await client.executeMultiple(SCHEMA);
  const db = wrap(client);

  // Run fn(txDb) inside a write transaction.
  db.tx = async (fn) => {
    const t = await client.transaction('write');
    try {
      const out = await fn(wrap(t));
      await t.commit();
      return out;
    } catch (err) {
      await t.rollback().catch(() => {});
      throw err;
    } finally {
      t.close();
    }
  };
  db.close = () => client.close();
  return db;
}

module.exports = { openDb, toPg };
